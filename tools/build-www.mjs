// Assemble the offline folder Capacitor copies into the iOS and Android apps.
// GitHub Pages keeps serving the repo root. This script does not edit it.
// PLAY_BUILD=1 writes the closed-test copy: every chapter open, and no
// payment URL in www/. The default copy keeps the website Season Pass.
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const www = join(root, 'www');
const play = process.env.PLAY_BUILD === '1';

const files = [
  'index.html',
  'style.css',
  'manifest.webmanifest',
  'game.js',
  'humans.js',
  'signup.js',
  'cinematics.js',
  'commercial.js',
  'season-pass.js',
  'play-build.js',
  'return-loop.js',
  'portraits.js',
  'feel.js',
  'voices.js',
  'sky.jpg',
  'book1-cover.jpg',
];

const dirs = [
  'vendor',
  'icons',
  'models',
  'media/shorts',
];

const banned = [
  /buy\.stripe\.com/i,
  /stripe\.com/i,
  /checkout\.stripe/i,
  /buy on web/i,
  /buy on the web/i,
  /paypal\.com/i,
];

function walk(dir, out){
  for (const name of readdirSync(dir)){
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

rmSync(www, { recursive: true, force: true });
mkdirSync(www, { recursive: true });

for (const file of files) {
  cpSync(join(root, file), join(www, file));
}
for (const dir of dirs) {
  cpSync(join(root, dir), join(www, dir), { recursive: true });
}
cpSync(join(root, 'native/native-shell.js'), join(www, 'native-shell.js'));

const indexPath = join(www, 'index.html');
let html = readFileSync(indexPath, 'utf8');
const tag = '<script src="native-shell.js"></script>';
if (!html.includes(tag)) {
  html = html.replace('</head>', `  ${tag}\n</head>`);
  writeFileSync(indexPath, html);
}

if (play) {
  writeFileSync(join(www, 'play-build.js'), [
    '// Closed-test Play bundle. Generated by tools/build-www.mjs.',
    '// GitHub Pages keeps play-build.js false. This copy is true.',
    'export const PLAY_BUILD = true;',
    '',
  ].join('\n'));

  // The title screen free chapter link reads like a paid upsell in the
  // Play copy. Drop the link and its form from www/index.html only.
  let playHtml = readFileSync(indexPath, 'utf8');
  playHtml = playHtml
    .replace(/[ \t]*<button class="loreLink" id="loreLink"[^>]*>[^<]*<\/button>\r?\n?/, '')
    .replace(/[ \t]*<form id="titleKit"[\s\S]*?<\/form>\r?\n?/, '');
  writeFileSync(indexPath, playHtml);

  const hits = [];
  if (/FREE FIRST CHAPTER|id="loreLink"|id="titleKit"/.test(playHtml)) {
    hits.push('free chapter link still in www/index.html');
  }
  for (const file of walk(www, [])){
    if (!/\.(html|css|js|mjs|json|webmanifest)$/.test(file)) continue;
    let body = readFileSync(file, 'utf8');
    const stripped = body
      .replace(/https:\/\/buy\.stripe\.com\/[A-Za-z0-9]+/g, '')
      .replace(/https:\/\/waking-season-pass\.matpcul\.workers\.dev/g, '')
      .replace(/\bStripe\b/g, '');
    if (stripped !== body) writeFileSync(file, stripped);
    for (const rule of banned){
      if (rule.test(stripped)) hits.push(rule + ' in ' + file);
    }
    if (/\bStripe\b/.test(stripped)) hits.push('Stripe in ' + file);
  }
  const flag = readFileSync(join(www, 'play-build.js'), 'utf8');
  if (!flag.includes('export const PLAY_BUILD = true;')) {
    hits.push('play-build.js was not set true');
  }
  if (hits.length){
    console.error(hits.join('\n'));
    process.exit(1);
  }
  console.log('play bundle written to www/ (chapters open, payment urls stripped)');
} else {
  console.log('offline bundle written to www/');
}
